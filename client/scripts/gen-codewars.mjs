// Generates src/data/codewars.js from the sibling data-structures-practice repo.
//
// The handbook builds offline, so the solutions are read once here and the
// result is committed — nothing at build time reaches outside this repo. Rerun
// after adding katas:
//
//   npm run gen:codewars
//
// Source directory defaults to the sibling checkout and can be overridden:
//
//   CODEWARS_DIR=/path/to/codewars npm run gen:codewars

import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))

const SOURCE =
  process.env.CODEWARS_DIR ??
  resolve(here, '../../../../data-structures-practice/codewars')

const CATEGORIES = join(here, 'categories.json')
const OUT = resolve(here, '../src/data/codewars.js')

// Words that look wrong in Title Case when split on underscores.
const ACRONYMS = new Map(
  Object.entries({
    dna: 'DNA',
    rna: 'RNA',
    csv: 'CSV',
    bmi: 'BMI',
    rps: 'RPS',
    pin: 'PIN',
    rot13: 'ROT13',
    tiy: 'TIY',
    nb: 'NB',
    db: 'DB',
    str: 'Str',
    arr: 'Arr',
  }),
)

function titleFor(name) {
  return name
    .split('_')
    .map((word) => ACRONYMS.get(word) ?? word[0].toUpperCase() + word.slice(1))
    .join(' ')
}

async function main() {
  const categories = JSON.parse(await readFile(CATEGORIES, 'utf8'))

  let files
  try {
    files = (await readdir(SOURCE)).filter((f) => f.endsWith('.py')).sort()
  } catch (error) {
    throw new Error(
      `Cannot read ${SOURCE}.\n` +
        `Set CODEWARS_DIR to the codewars folder of the data-structures-practice repo.\n` +
        `(${error.message})`,
    )
  }

  // A file with no category, or a category with no file, means the two repos
  // have drifted — fail loudly rather than silently emitting a partial page.
  const names = files.map((f) => f.slice(0, -3))
  const missing = names.filter((n) => !categories[n])
  const stale = Object.keys(categories).filter((n) => !names.includes(n))
  if (missing.length || stale.length) {
    throw new Error(
      [
        missing.length && `Not in categories.json: ${missing.join(', ')}`,
        stale.length && `In categories.json but not on disk: ${stale.join(', ')}`,
      ]
        .filter(Boolean)
        .join('\n'),
    )
  }

  const items = []
  for (const name of names) {
    const code = (await readFile(join(SOURCE, `${name}.py`), 'utf8')).trimEnd()
    items.push({
      name,
      title: titleFor(name),
      category: categories[name],
      code,
      lines: code.split('\n').length,
    })
  }

  const counts = new Map()
  for (const item of items) {
    counts.set(item.category, (counts.get(item.category) ?? 0) + 1)
  }
  const tally = [...counts]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([category, n]) => `\`${category}\` — ${n} ${n === 1 ? 'solution' : 'solutions'}`)

  const guide = {
    id: 'codewars',
    label: 'Codewars Solutions',
    section: 'Practice',
    lede: `${items.length} Python solutions, filterable by the concept each one leans on.`,
    blocks: [
      { type: 'h2', text: 'At a glance' },
      {
        type: 'p',
        text:
          `${items.length} katas solved in Python, from ` +
          '[the practice repo](https://github.com/gadm12/data-structures-practice). ' +
          'Categories are a rough sort by the concept each solution leans on, not by kata rank.',
      },
      { type: 'ul', items: tally },
      { type: 'h2', text: 'All solutions' },
      {
        type: 'p',
        text: 'Pick a category to narrow the list, then open a solution to read or copy it.',
      },
      { type: 'solutions', items },
      { type: 'h2', text: 'Regenerating this page' },
      {
        type: 'p',
        text: 'This page is generated from the solution files — edit those, not `src/data/codewars.js`.',
      },
      { type: 'code', lang: 'bash', code: 'cd client\nnpm run gen:codewars' },
    ],
  }

  const banner =
    '// GENERATED by scripts/gen-codewars.mjs — do not edit by hand.\n' +
    '// Source: the codewars/ folder of the data-structures-practice repo.\n' +
    '// Categories: scripts/categories.json. Rerun: npm run gen:codewars\n\n'

  await writeFile(OUT, `${banner}export const codewars = ${JSON.stringify(guide, null, 2)}\n`)

  console.log(`Wrote ${OUT}`)
  console.log(`${items.length} solutions across ${counts.size} categories.`)
}

main().catch((error) => {
  console.error(error.message)
  process.exit(1)
})
